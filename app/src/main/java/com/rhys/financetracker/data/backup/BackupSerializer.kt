        put("frequency", rule.frequency.name)
        put("interval", rule.interval)
        put("startDate", rule.startDate.toString())
        putOpt("endDate", rule.endDate?.toString())
        putOpt("maxOccurrences", rule.maxOccurrences)
        put("occurrencesGenerated", rule.occurrencesGenerated)
        put("nextDueDate", rule.nextDueDate.toString())
        putOpt("lastGeneratedDate", rule.lastGeneratedDate?.toString())
        put("accountId", rule.accountId)
        putOpt("transferAccountId", rule.transferAccountId)
        putOpt("categoryId", rule.categoryId)
        putOpt("personId", rule.personId)
        putOpt("savingsGoalId", rule.savingsGoalId)
        put("mode", rule.mode.name)
        putOpt("reminderDaysBefore", rule.reminderDaysBefore)
        put("isVariableAmount", rule.isVariableAmount)
        putOpt("notes", rule.notes)
        put("isPaused", rule.isPaused)
        put("isArchived", rule.isArchived)
        put("createdAt", rule.createdAt)
        put("updatedAt", rule.updatedAt)
    }

    fun recurringFromJson(json: JSONObject): RecurringRuleEntity {
        val start = json.optDate("startDate") ?: LocalDate.now()
        return RecurringRuleEntity(
            id = json.optLong("id", 0L),
            name = json.optString("name", "Recurring payment"),
            amountMinor = json.optLong("amountMinor", 0L),
            type = json.optEnum("type", TransactionType.EXPENSE) { TransactionType.valueOf(it) },
            frequency = json.optEnum("frequency", Frequency.MONTHLY) { Frequency.valueOf(it) },
            interval = json.optInt("interval", 1),
            startDate = start,
            endDate = json.optDate("endDate"),
            maxOccurrences = json.optIntOrNull("maxOccurrences"),
            occurrencesGenerated = json.optInt("occurrencesGenerated", 0),
            nextDueDate = json.optDate("nextDueDate") ?: start,
            lastGeneratedDate = json.optDate("lastGeneratedDate"),
            accountId = json.optLong("accountId", 0L),
            transferAccountId = json.optLongOrNull("transferAccountId"),
            categoryId = json.optLongOrNull("categoryId"),
            personId = json.optLongOrNull("personId"),
            savingsGoalId = json.optLongOrNull("savingsGoalId"),
            mode = json.optEnum("mode", RecurrenceMode.AUTO_POST) { RecurrenceMode.valueOf(it) },
            reminderDaysBefore = json.optIntOrNull("reminderDaysBefore"),
            isVariableAmount = json.optBoolean("isVariableAmount", false),
            notes = json.optStringOrNull("notes"),
            isPaused = json.optBoolean("isPaused", false),
            isArchived = json.optBoolean("isArchived", false),
            createdAt = json.optLong("createdAt", System.currentTimeMillis()),
            updatedAt = json.optLong("updatedAt", System.currentTimeMillis()),
        )
    }

