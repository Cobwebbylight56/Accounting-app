/**
 * Converts entities to and from the backup JSON.
 *
 * The mapping is written out by hand rather than generated by reflection so
 * that renaming a Kotlin property can never silently change the file format —
 * a backup taken today must still restore in five years' time.
 *
 * Reads are forgiving: every `opt…` call has a default, so a file written by an
 * older version restores without complaint.
 */
@Singleton
class BackupSerializer @Inject constructor() {

    // -------------------------------------------------------------- people

    fun personToJson(person: PersonEntity): JSONObject = JSONObject().apply {
        put("id", person.id)
        put("name", person.name)
        put("colorHex", person.colorHex)
        put("isShared", person.isShared)
        put("sortOrder", person.sortOrder)
        putOpt("notes", person.notes)
        put("isArchived", person.isArchived)
        put("createdAt", person.createdAt)
        put("updatedAt", person.updatedAt)
    }

    fun personFromJson(json: JSONObject): PersonEntity = PersonEntity(
        id = json.optLong("id", 0L),
        name = json.optString("name", "Unnamed"),
        colorHex = json.optString("colorHex", "#455A64"),
        isShared = json.optBoolean("isShared", false),
        sortOrder = json.optInt("sortOrder", 0),
        notes = json.optStringOrNull("notes"),
        isArchived = json.optBoolean("isArchived", false),
        createdAt = json.optLong("createdAt", System.currentTimeMillis()),
        updatedAt = json.optLong("updatedAt", System.currentTimeMillis()),
    )

    // ------------------------------------------------------------ accounts

    fun accountToJson(account: AccountEntity): JSONObject = JSONObject().apply {
        put("id", account.id)
        put("name", account.name)
        put("type", account.type.name)
        putOpt("personId", account.personId)
        put("openingBalanceMinor", account.openingBalanceMinor)
        put("openingBalanceDate", account.openingBalanceDate.toString())
        put("currencyCode", account.currencyCode)
        put("overdraftLimitMinor", account.overdraftLimitMinor)
        putOpt("lowBalanceThresholdMinor", account.lowBalanceThresholdMinor)
        putOpt("creditLimitMinor", account.creditLimitMinor)
        putOpt("interestRatePercent", account.interestRatePercent)
        put("colorHex", account.colorHex)
        put("includeInNetWorth", account.includeInNetWorth)
        putOpt("countsAsSavings", account.countsAsSavings)
        put("isShared", account.isShared)
        put("sortOrder", account.sortOrder)
        putOpt("notes", account.notes)
        put("isArchived", account.isArchived)
        put("createdAt", account.createdAt)
        put("updatedAt", account.updatedAt)
    }

    fun accountFromJson(json: JSONObject): AccountEntity = AccountEntity(
        id = json.optLong("id", 0L),
        name = json.optString("name", "Account"),
        type = json.optEnum("type", AccountType.OTHER) { AccountType.valueOf(it) },
        personId = json.optLongOrNull("personId"),
        openingBalanceMinor = json.optLong("openingBalanceMinor", 0L),
        openingBalanceDate = json.optDate("openingBalanceDate") ?: LocalDate.now(),
        currencyCode = json.optString("currencyCode", "GBP"),
        overdraftLimitMinor = json.optLong("overdraftLimitMinor", 0L),
        lowBalanceThresholdMinor = json.optLongOrNull("lowBalanceThresholdMinor"),
        creditLimitMinor = json.optLongOrNull("creditLimitMinor"),
        interestRatePercent = if (json.has("interestRatePercent") &&
            !json.isNull("interestRatePercent")
        ) {
            json.optDouble("interestRatePercent")
        } else {
            null
        },
        colorHex = json.optString("colorHex", "#455A64"),
        includeInNetWorth = json.optBoolean("includeInNetWorth", true),
        countsAsSavings = if (json.has("countsAsSavings")) {
            json.optBoolean("countsAsSavings")
        } else {
            null
        },
        isShared = json.optBoolean("isShared", false),
        sortOrder = json.optInt("sortOrder", 0),
        notes = json.optStringOrNull("notes"),
        isArchived = json.optBoolean("isArchived", false),
        createdAt = json.optLong("createdAt", System.currentTimeMillis()),
        updatedAt = json.optLong("updatedAt", System.currentTimeMillis()),
    )

    // ---------------------------------------------------------- categories

    fun categoryToJson(category: CategoryEntity): JSONObject = JSONObject().apply {
        put("id", category.id)
        put("name", category.name)
        put("kind", category.kind.name)
        put("colorHex", category.colorHex)
        putOpt("iconKey", category.iconKey)
        putOpt("parentId", category.parentId)
        putOpt("monthlyBudgetMinor", category.monthlyBudgetMinor)
        put("sortOrder", category.sortOrder)
        put("isSystem", category.isSystem)
        put("isArchived", category.isArchived)
        put("createdAt", category.createdAt)
        put("updatedAt", category.updatedAt)
    }

    fun categoryFromJson(json: JSONObject): CategoryEntity = CategoryEntity(
        id = json.optLong("id", 0L),
        name = json.optString("name", "Category"),
        kind = json.optEnum("kind", CategoryKind.EXPENSE) { CategoryKind.valueOf(it) },
        colorHex = json.optString("colorHex", "#455A64"),
        iconKey = json.optStringOrNull("iconKey"),
        parentId = json.optLongOrNull("parentId"),
        monthlyBudgetMinor = json.optLongOrNull("monthlyBudgetMinor"),
        sortOrder = json.optInt("sortOrder", 0),
        isSystem = json.optBoolean("isSystem", false),
        isArchived = json.optBoolean("isArchived", false),
        createdAt = json.optLong("createdAt", System.currentTimeMillis()),
        updatedAt = json.optLong("updatedAt", System.currentTimeMillis()),
    )

    // -------------------------------------------------------- transactions

    fun transactionToJson(transaction: TransactionEntity): JSONObject = JSONObject().apply {
        put("id", transaction.id)
        put("amountMinor", transaction.amountMinor)
        put("type", transaction.type.name)
        put("date", transaction.date.toString())
        put("description", transaction.description)
        put("accountId", transaction.accountId)
        putOpt("transferAccountId", transaction.transferAccountId)
        putOpt("categoryId", transaction.categoryId)
        putOpt("personId", transaction.personId)
        putOpt("recurringRuleId", transaction.recurringRuleId)
        putOpt("savingsGoalId", transaction.savingsGoalId)
        putOpt("notes", transaction.notes)
        put("isConfirmed", transaction.isConfirmed)
        put("isCleared", transaction.isCleared)
        putOpt("tags", transaction.tags)
        // Both of these decide what a later import does with the row. Without
        // the fingerprint, re-importing a statement after a restore adds every
        // row a second time; without the source, everything restored looks
        // hand-typed and the protection a bank record has is lost.
        putOpt("importHash", transaction.importHash)
        put("source", transaction.source.name)
        put("isArchived", transaction.isArchived)
        put("createdAt", transaction.createdAt)
        put("updatedAt", transaction.updatedAt)
    }

    fun transactionFromJson(json: JSONObject): TransactionEntity = TransactionEntity(
        id = json.optLong("id", 0L),
        amountMinor = json.optLong("amountMinor", 0L),
        type = json.optEnum("type", TransactionType.EXPENSE) { TransactionType.valueOf(it) },
        date = json.optDate("date") ?: LocalDate.now(),
        description = json.optString("description", "Transaction"),
        accountId = json.optLong("accountId", 0L),
        transferAccountId = json.optLongOrNull("transferAccountId"),
        categoryId = json.optLongOrNull("categoryId"),
        personId = json.optLongOrNull("personId"),
        recurringRuleId = json.optLongOrNull("recurringRuleId"),
        savingsGoalId = json.optLongOrNull("savingsGoalId"),
        notes = json.optStringOrNull("notes"),
        isConfirmed = json.optBoolean("isConfirmed", true),
        isCleared = json.optBoolean("isCleared", true),
        tags = json.optStringOrNull("tags"),
        importHash = json.optStringOrNull("importHash"),
        // A backup written before this was recorded restores as UNKNOWN, the
        // weakest source, so an old backup is corrected by a statement rather
        // than shielded from one.
        source = json.optEnum("source", RecordSource.UNKNOWN) { RecordSource.valueOf(it) },
        isArchived = json.optBoolean("isArchived", false),
        createdAt = json.optLong("createdAt", System.currentTimeMillis()),
        updatedAt = json.optLong("updatedAt", System.currentTimeMillis()),
    )

    // ------------------------------------------------------------ recurring

