    /** Reads a JSON array into a list, skipping any element that will not parse. */
    fun <T> readArray(array: JSONArray?, parse: (JSONObject) -> T): List<T> {
        if (array == null) return emptyList()
        val result = mutableListOf<T>()
        for (index in 0 until array.length()) {
            val item = array.optJSONObject(index) ?: continue
            runCatching { parse(item) }.onSuccess { result += it }
        }
        return result
    }

    fun <T> writeArray(items: List<T>, convert: (T) -> JSONObject): JSONArray =
        JSONArray().also { array -> items.forEach { array.put(convert(it)) } }
}

// ----------------------------------------------------- JSONObject helpers

/** `optString` returns "" for a missing key; this returns null, which is what entities expect. */
internal fun JSONObject.optStringOrNull(key: String): String? =
    if (!has(key) || isNull(key)) null else optString(key).takeIf { it.isNotEmpty() }

internal fun JSONObject.optLongOrNull(key: String): Long? =
    if (!has(key) || isNull(key)) null else optLong(key)

internal fun JSONObject.optIntOrNull(key: String): Int? =
    if (!has(key) || isNull(key)) null else optInt(key)

internal fun JSONObject.optDate(key: String): LocalDate? =
    optStringOrNull(key)?.let { runCatching { LocalDate.parse(it) }.getOrNull() }

/** Reads an enum by name, falling back to [fallback] if the name is unknown. */
internal fun <T : Enum<T>> JSONObject.optEnum(key: String, fallback: T, parse: (String) -> T): T =
    optStringOrNull(key)?.let { runCatching { parse(it) }.getOrNull() } ?: fallback
