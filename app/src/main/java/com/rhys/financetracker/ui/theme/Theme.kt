/** Makes the semantic finance colours available anywhere in the tree. */
val LocalFinanceColors = staticCompositionLocalOf { FinanceColors.Light }

/**
 * The app theme.
 *
 * @param themeMode the user's light/dark preference.
 * @param dynamicColor when true and the device supports it, the Material You
 *   palette from the wallpaper is used for the general chrome.  The income,
 *   expense and chart colours are never taken from the wallpaper, because their
 *   meaning must not change.
 */
@Composable
fun FinanceTrackerTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        darkTheme -> DarkScheme
        else -> LightScheme
    }

    val financeColors = if (darkTheme) FinanceColors.Dark else FinanceColors.Light

    CompositionLocalProvider(LocalFinanceColors provides financeColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = FinanceTypography,
            content = content,
        )
    }
}

/** Shorthand: `FinanceTheme.colors.income`. */
object FinanceTheme {
    val colors: FinanceColors
        @Composable get() = LocalFinanceColors.current
}
